/*1.How have total orders and revenue changed over time, 
and are there any noticeable sales trends?*/

/*Purpose:
Identify sales growth patterns and seasonal trends to 
support business planning and revenue forecasting.*/

SELECT
    EXTRACT(YEAR FROM o.order_date) AS sales_year,
    EXTRACT(MONTH FROM o.order_date) AS sales_month,
    ROUND(
        SUM(od.quantity * p.unit_price * (1 - od.discount))::NUMERIC,
        2
    ) AS total_revenue
FROM orders o
INNER JOIN order_details od
    ON o.order_id = od.order_id
INNER JOIN products p
    ON od.product_id = p.product_id
GROUP BY
    EXTRACT(YEAR FROM o.order_date),
    EXTRACT(MONTH FROM o.order_date)
ORDER BY
    sales_year,
    sales_month;

/*What above query does:
- Groups orders by year and month.
- Calculates the revenue for each month.
- Shows whether revenue increased or decreased over time.*/

--2.Which products are the best-selling and worst-selling based on sales quantity?

/*Purpose:
Identify high-performing and underperforming products 
to support inventory management and product planning.*/

SELECT
    p.product_id,
    p.product_name,
    SUM(od.quantity) AS total_quantity_sold
FROM products p
INNER JOIN order_details od
    ON p.product_id = od.product_id
GROUP BY
    p.product_id,
    p.product_name
ORDER BY
    total_quantity_sold DESC;

--3.Which customers generate the highest number of orders and contribute the most revenue?

/*Purpose:
Recognize valuable customers to improve customer relationship management 
and support targeted marketing strategies.*/

SELECT
    c.customer_id,
    c.company_name,
    COUNT(DISTINCT o.order_id) AS total_orders,
    ROUND(
        SUM(
            od.quantity * p.unit_price * (1 - od.discount)
        )::NUMERIC,
        2
    ) AS total_revenue
FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id
INNER JOIN order_details od
    ON o.order_id = od.order_id
INNER JOIN products p
    ON od.product_id = p.product_id
GROUP BY
    c.customer_id,
    c.company_name
ORDER BY
    total_revenue DESC;

--4.Are shipping costs consistent across different shipping providers?

/*Purpose:
Compare freight rates across shipping companies to identify 
opportunities to optimize costs and improve shipping efficiency.*/

SELECT
    s.shipper_id,
    s.company_name AS shipping_company,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.freight)::NUMERIC, 2) AS total_shipping_cost
FROM shippers s
INNER JOIN orders o
    ON s.shipper_id = o.shipper_id
GROUP BY
    s.shipper_id,
    s.company_name
ORDER BY
    total_shipping_cost DESC;
--Notes:In this dataset,freight represents the shipping charge recorded for each order.	

/* 5.How efficient is the delivery process, 
and how many orders are delivered on time versus late?*/

/*Purpose:
We want to compare the actual shipping date with the required 
delivery date to determine whether orders were shipped on time or late.*/

SELECT
    CASE
        WHEN shipped_date IS NULL THEN 'Not Shipped'
        WHEN shipped_date <= required_date THEN 'On Time'
        ELSE 'Late'
    END AS delivery_status,
    COUNT(*) AS total_orders
FROM orders
GROUP BY
    CASE
        WHEN shipped_date IS NULL THEN 'Not Shipped'
        WHEN shipped_date <= required_date THEN 'On Time'
        ELSE 'Late'
    END
ORDER BY total_orders DESC;

/* Note: This query measures whether orders were shipped by the required date, 
not whether customers physically received them by that date.*/








