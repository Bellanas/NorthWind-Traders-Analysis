-----The Key Metrics------
--Total Orders
SELECT
    COUNT(order_id) AS total_orders
FROM orders;

--Total Revenue
--Quantity × Unit Price × (1 − Discount)

SELECT
    ROUND(
        SUM(
            od.quantity * p.unit_price *
            (1 - od.discount)
        )::NUMERIC, 2
    ) AS total_revenue
FROM order_details od
INNER JOIN products p
    ON od.product_id = p.product_id;

--Average Order Value
--This means the average revenue generated by each order.

SELECT
    ROUND(
        SUM(
            od.quantity * p.unit_price *
            (1 - od.discount)
        ) / COUNT(DISTINCT od.order_id),
        2
    ) AS average_order_value
FROM order_details od
INNER JOIN products p
    ON od.product_id = p.product_id;

--Average Shipping Time (Shipping Efficiency)
/*We calculate the number of days between the order date and shipped date,
approximately 9 days from order date to shipped date.*/

SELECT
    ROUND(
        AVG(shipped_date - order_date),
        2
    ) AS average_shipping_days
FROM orders
WHERE shipped_date IS NOT NULL;



